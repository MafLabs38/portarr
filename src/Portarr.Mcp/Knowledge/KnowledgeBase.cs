using System.Globalization;
using System.Text;
using Portarr.Core.Catalog;
using Portarr.Core.Status;
using Portarr.Mcp.Digest;

namespace Portarr.Mcp.Knowledge;

/// <summary>
/// The map of the fleet in Markdown (V5, D-69), generated from the live state on every read so it is never stale:
/// environments and machines with their hierarchy (VMs under their hypervisor), stacks and apps with their URLs,
/// roles and where they run, data assets and backup jobs, code repositories and images, and what the operator wrote
/// down (D-84): notes, how to reach each machine, network links and external providers. An assistant reads it
/// once to learn the infrastructure, then calls the tools for details. Same data as the pages, no secret.
/// </summary>
public sealed class KnowledgeBase
{
    // MCP resource identifiers: names in the protocol, not addresses to reach.
    [System.Diagnostics.CodeAnalysis.SuppressMessage("Minor Code Smell", "S1075:URIs should not be hardcoded", Justification = "An MCP resource identifier, not an address.")]
    public const string InfrastructureUri = "portarr://knowledge/infrastructure";

    [System.Diagnostics.CodeAnalysis.SuppressMessage("Minor Code Smell", "S1075:URIs should not be hardcoded", Justification = "An MCP resource identifier, not an address.")]
    public const string GlossaryUri = "portarr://knowledge/glossary";

    private readonly FleetDigest _digest;
    private readonly ICatalogService _catalogService;
    private readonly IFleetService _fleetService;

    public KnowledgeBase(FleetDigest digest, ICatalogService catalogService, IFleetService fleetService)
    {
        _digest = digest;
        _catalogService = catalogService;
        _fleetService = fleetService;
    }

    public string BuildInfrastructure()
    {
        var catalog = _catalogService.Current.Catalog;
        var overview = _digest.GetOverview();
        var infrastructure = _digest.GetInfrastructure(null);
        var data = _digest.GetDataCoverage(false);
        var maintenance = _digest.GetMaintenance("all");
        var apps = _fleetService.GetApps();

        var md = new StringBuilder();
        md.AppendLine("# Infrastructure knowledge base").AppendLine();
        Line(md, $"Generated by Portarr at {overview.GeneratedAt.UtcDateTime.ToString("u", CultureInfo.InvariantCulture)} from its live view. Portarr is read-only: it reports, the operator acts. Statuses, roles and codes: {GlossaryUri}.");
        md.AppendLine();

        WriteSummary(md, overview, infrastructure);
        WriteEnvironments(md, catalog, overview.Environments, infrastructure);
        WriteKnowledge(md, EnvironmentKnowledgeBuilder.Build(catalog, null));
        WriteApps(md, catalog, apps);
        WriteData(md, data);
        WriteMaintenance(md, maintenance);

        return md.ToString();
    }

    private static void WriteSummary(StringBuilder md, Overview overview, IReadOnlyList<InfrastructureLine> infrastructure)
    {
        var a = overview.Apps;
        var d = overview.Data;
        var m = overview.Maintenance;
        md.AppendLine("## Summary").AppendLine();
        Line(md, $"- Apps: {a.Total} ({a.Healthy} healthy, {a.Degraded} degraded, {a.Down} down, {a.Unknown} unknown)");
        Line(md, $"- Environments: {overview.Environments.Count}; machines: {infrastructure.Sum(e => e.Machines.Count)}");
        Line(md, $"- Data followed: {d.Followed} ({d.Protected} protected, {d.Late} late, {d.Failed} failed, {d.Missing} missing, {d.Waiting} waiting for a first run, {d.NotSetUp} with a tool not set up, {d.Unknown} unknown); {d.CriticalOffsite} of {d.CriticalAssets} critical assets have an off-site copy ({d.CriticalOffsitePending} pending a first run)");
        Line(md, $"- Code: {m.Repositories} repositories ({m.CriticalOrHighAlerts} critical or high alerts, {m.CiFailing} with CI failing); images: {m.Images} running ({m.ImagesBehind} behind, {m.ImagesMajor} with a new major version)");
        if (overview.NeedsAttention.Count > 0)
        {
            Line(md, "- Needs attention:");
            foreach (var finding in overview.NeedsAttention)
            {
                Line(md, $"  - {finding.Level} · {finding.Kind} ({finding.Count}): {string.Join("; ", finding.Subjects)}");
            }
        }

        md.AppendLine();
    }

    private static void WriteEnvironments(StringBuilder md, Catalog catalog, IReadOnlyList<EnvironmentLine> environments, IReadOnlyList<InfrastructureLine> infrastructure)
    {
        md.AppendLine("## Environments and machines").AppendLine();
        Line(md, "Indentation shows where things run: a VM is listed under the hypervisor it runs on.");
        md.AppendLine();

        var known = catalog.Environments.Select(e => e.Id).ToHashSet(StringComparer.Ordinal);
        var lines = environments.ToDictionary(e => e.Id, StringComparer.Ordinal);
        var machines = infrastructure.ToDictionary(e => e.Id, StringComparer.Ordinal);

        foreach (var root in catalog.Environments.Where(e => e.Host is null || !known.Contains(e.Host)))
        {
            WriteEnvironment(md, catalog, root, lines, machines, 0);
        }

        md.AppendLine();
    }

    private static void WriteEnvironment(
        StringBuilder md,
        Catalog catalog,
        CatalogEnvironment environment,
        Dictionary<string, EnvironmentLine> lines,
        Dictionary<string, InfrastructureLine> infrastructure,
        int depth)
    {
        var indent = new string(' ', depth * 2);
        var line = lines.GetValueOrDefault(environment.Id);
        var address = environment.Address is null ? string.Empty : $", LAN address {environment.Address}";
        var hosted = environment.Host is null ? string.Empty : $", VM on {line?.HostedOn ?? environment.Host}";
        var error = line?.Error is null ? string.Empty : $" ({line.Error})";
        Line(md, $"{indent}- **{environment.Name}** (`{environment.Id}`, {environment.Runtime}{address}{hosted}): {line?.Connection ?? "pending"}{error}, {line?.Workloads ?? 0} workloads");

        foreach (var machine in infrastructure.GetValueOrDefault(environment.Id)?.Machines ?? [])
        {
            Line(md, $"{indent}  - {DescribeMachine(machine)}");
        }

        // Nodes of a cluster that are VMs on this environment (D-59).
        foreach (var cluster in catalog.Environments.Where(e => e.MachineHosts is not null))
        {
            foreach (var node in cluster.MachineHosts!.Where(n => n.Value == environment.Id).Select(n => n.Key).Order(StringComparer.Ordinal))
            {
                Line(md, $"{indent}  - VM: node `{node}` of **{cluster.Name}** (`{cluster.Id}`)");
            }
        }

        foreach (var guest in catalog.Environments.Where(e => e.Host == environment.Id && e.Id != environment.Id))
        {
            WriteEnvironment(md, catalog, guest, lines, infrastructure, depth + 1);
        }
    }

    private static string DescribeMachine(MachineLine machine)
    {
        var kind = machine.Kind == "kubernetes-node" ? "node" : "Docker host";
        var size = $"{Number(machine.Cpu.Capacity)} cores, {Number(machine.Memory.Capacity)} GiB";
        var scope = machine.Scope == "containers" ? " (sum of its containers)" : string.Empty;
        var load = $"now CPU {Percent(machine.Cpu.NowPercent)}, memory {Percent(machine.Memory.NowPercent)}{scope}";
        var ready = machine.Ready == false ? ", NOT READY" : string.Empty;
        var roles = machine.Roles.Count > 0 ? $", roles {string.Join("/", machine.Roles)}" : string.Empty;
        var hosted = machine.HostedOn is null ? string.Empty : $", VM on {machine.HostedOn}";
        var top = machine.TopConsumers.Count == 0
            ? string.Empty
            : $"; top consumers: {string.Join(", ", machine.TopConsumers.Select(c => $"{c.Workload} ({Number(c.CpuCores)} cores, {Number(c.MemoryGiB)} GiB)"))}";
        return $"{kind} `{machine.Name}`: {size}{roles}{hosted}{ready}; {load}; {machine.Workloads} workloads{top}";
    }

    private static void WriteApps(StringBuilder md, Catalog catalog, IReadOnlyList<AppView> apps)
    {
        md.AppendLine("## Stacks and apps").AppendLine();
        var byId = apps.ToDictionary(a => a.App.Id, StringComparer.Ordinal);

        foreach (var stack in catalog.Stacks)
        {
            Line(md, $"### Stack {Cell(stack.Name)} (`{stack.Id}`)");
            if (stack.Description is not null)
            {
                md.AppendLine().AppendLine(Cell(stack.Description));
            }

            if (stack.Notes is not null)
            {
                md.AppendLine().AppendLine(stack.Notes);
            }

            md.AppendLine();
            var members = stack.Members.Select(m => byId.GetValueOrDefault(m.AppId)).OfType<AppView>().ToList();
            WriteAppTable(md, members);
            WriteAppNotes(md, members);
        }

        var loose = apps.Where(a => a.Stack is null).ToList();
        if (loose.Count > 0)
        {
            md.AppendLine("### Apps outside a stack").AppendLine();
            WriteAppTable(md, loose);
            WriteAppNotes(md, loose);
        }
    }

    private static void WriteAppTable(StringBuilder md, IEnumerable<AppView> apps)
    {
        md.AppendLine("| App | Status | Role | Runs on | URLs |");
        md.AppendLine("|---|---|---|---|---|");
        foreach (var app in apps)
        {
            var status = app.Status.Status == HealthStatus.Healthy ? "Healthy" : $"{app.Status.Status}: {StatusText.Of(app.Status)}";
            var runsOn = string.Join(", ", app.Workloads.Select(w => $"{w.EnvironmentId}/{w.Workload?.Node ?? w.Name}{(w.Workload?.Node is null ? string.Empty : $"/{w.Name}")}"));
            var urls = string.Join(" ", app.Urls.Select(u => $"{u.Scope.ToString().ToLowerInvariant()}: {SafeUrl.Of(u.Href)}"));
            var role = app.Role?.ToString().ToLowerInvariant() ?? "-";
            Line(md, $"| {Cell(app.App.Name)} (`{app.App.Id}`) | {Cell(status)} | {role} | {Cell(runsOn)} | {Cell(urls)} |");
        }

        md.AppendLine();
    }

    private static void WriteAppNotes(StringBuilder md, IReadOnlyList<AppView> apps)
    {
        var noted = apps.Where(a => a.App.Notes is not null).ToList();
        foreach (var app in noted.Select(a => a.App))
        {
            Line(md, $"- Notes on {app.Name} (`{app.Id}`): {Indent(app.Notes!, "  ")}");
        }

        if (noted.Count > 0)
        {
            md.AppendLine();
        }
    }

    /// <summary>What the operator wrote down (D-84): how to reach the machines, the network links, the providers.</summary>
    private static void WriteKnowledge(StringBuilder md, EnvironmentKnowledge knowledge)
    {
        var described = knowledge.Environments.Where(e => e.Notes is not null || e.Access is not null || e.Machines.Count > 0).ToList();
        if (described.Count == 0 && knowledge.Links.Count == 0 && knowledge.Providers.Count == 0)
        {
            return;
        }

        md.AppendLine("## Access, network and providers").AppendLine();
        Line(md, "Written by the operator in the catalog (never secrets: key files and variables are named, not given). Details per environment: get_environment_knowledge.");
        md.AppendLine();

        foreach (var environment in described)
        {
            WriteKnowledgeEnvironment(md, environment);
        }

        WriteLinks(md, knowledge.Links);
        WriteProviders(md, knowledge.Providers);
        md.AppendLine();
    }

    private static void WriteKnowledgeEnvironment(StringBuilder md, EnvironmentKnowledgeLine environment)
    {
        Line(md, $"- **{environment.Name}** (`{environment.Id}`){Notes(environment.Notes, "  ")}");
        WriteAccess(md, environment.Access, "  ");
        foreach (var machine in environment.Machines)
        {
            var hosted = machine.HostedOn is null ? string.Empty : $", VM on {machine.HostedOn}";
            Line(md, $"  - machine `{machine.Name}`{hosted}{Notes(machine.Notes, "    ")}");
            WriteAccess(md, machine.Access, "    ");
        }
    }

    private static void WriteLinks(StringBuilder md, IReadOnlyList<LinkLine> links)
    {
        if (links.Count == 0)
        {
            return;
        }

        md.AppendLine().AppendLine("### Network links").AppendLine();
        foreach (var link in links)
        {
            var name = link.Name is null ? string.Empty : $" {link.Name}";
            var network = link.Network is null ? string.Empty : $", network {link.Network}";
            Line(md, $"- `{link.From}` ⇄ `{link.To}`: {link.Kind}{name}{network} (`{link.Id}`){Notes(link.Notes, "  ")}");
        }
    }

    private static void WriteProviders(StringBuilder md, IReadOnlyList<ProviderLine> providers)
    {
        if (providers.Count == 0)
        {
            return;
        }

        md.AppendLine().AppendLine("### External providers").AppendLine();
        foreach (var provider in providers)
        {
            var console = provider.Console is null ? string.Empty : $", console {provider.Console}";
            var account = provider.Account is null ? string.Empty : $", account {provider.Account}";
            var used = provider.UsedBy.Count == 0 ? string.Empty : $"; used by {string.Join(", ", provider.UsedBy)}";
            Line(md, $"- **{provider.Name}** (`{provider.Id}`, {provider.Kind}{console}{account}){used}{Notes(provider.Notes, "  ")}");
        }
    }

    private static void WriteAccess(StringBuilder md, AccessLine? access, string indent)
    {
        if (access is null)
        {
            return;
        }

        if (access.Ssh is { } ssh)
        {
            var target = SshTarget(ssh);
            var key = ssh.Key is null ? string.Empty : $" (key file {ssh.Key})";
            var jump = ssh.Jump is null || ssh.Alias is null ? string.Empty : $" (through {ssh.Jump})";
            Line(md, $"{indent}- reach: `{ssh.Command}`{target}{jump}{key}");
        }

        foreach (var console in access.Consoles)
        {
            Line(md, $"{indent}- console: {console.Label} {console.Url}");
        }

        if (access.Notes is not null)
        {
            Line(md, $"{indent}- access notes: {Indent(access.Notes, indent + "  ")}");
        }
    }

    private static string Notes(string? notes, string indent) => notes is null ? string.Empty : $": {Indent(notes, indent)}";

    /// <summary>Multi-line notes kept inside their list item.</summary>
    private static string Indent(string text, string indent) => text.ReplaceLineEndings("\n" + indent);

    private static void WriteData(StringBuilder md, DataDigest data)
    {
        md.AppendLine("## Data and backups").AppendLine();
        foreach (var asset in data.Assets)
        {
            Line(md, $"- `{asset.Name}` ({asset.Kind}, {asset.Importance}, app {asset.App}, {asset.Environment}): **{asset.State}**; local {Copy(asset.Local)}; off-site {Copy(asset.Offsite)}");
        }

        if (data.Truncated)
        {
            Line(md, $"- … more assets: call get_data_coverage.");
        }

        if (data.Sources.Count > 0)
        {
            md.AppendLine().AppendLine("Backup tools read:").AppendLine();
            foreach (var source in data.Sources)
            {
                Line(md, $"- **{source.Tool}** on {source.Environment}: {(source.Error is null ? $"{source.Jobs} jobs" : source.Error)}");
            }
        }

        md.AppendLine();
    }

    private static string Copy(CopyLine? copy)
    {
        if (copy is null)
        {
            return "not expected";
        }

        var last = copy.LastSuccessAt is { } at ? $", last success {at.UtcDateTime.ToString("u", CultureInfo.InvariantCulture)}" : string.Empty;
        var reason = copy.Reason is null ? string.Empty : $" ({copy.Reason})";
        return $"{copy.State}{reason}{last}";
    }

    /// <summary>" (user@host:port)" when the access names an alias and a host (the alias alone is the command), else nothing.</summary>
    private static string SshTarget(SshLine ssh)
    {
        if (ssh.Alias is null || ssh.Host is null)
        {
            return string.Empty;
        }

        var user = ssh.User is null ? string.Empty : ssh.User + "@";
        var port = ssh.Port is { } number ? ":" + number.ToString(CultureInfo.InvariantCulture) : string.Empty;
        return $" ({user}{ssh.Host}{port})";
    }

    private static string DeployedText(RepositoryLine repository)
    {
        if (!repository.Deployed)
        {
            return "not deployed here";
        }

        return repository.Apps.Count > 0 ? $"deployed as {string.Join(", ", repository.Apps)}" : "deployed";
    }

    private static void WriteMaintenance(StringBuilder md, MaintenanceDigest maintenance)
    {
        md.AppendLine("## Code and images").AppendLine();
        foreach (var repository in maintenance.Repositories)
        {
            var deployed = DeployedText(repository);
            var ci = repository.Ci is null ? string.Empty : $"; CI {repository.Ci}";
            Line(md, $"- `{repository.FullName}` ({deployed}): Dependabot {repository.Dependabot}; code scanning {repository.CodeScanning}{ci}");
        }

        foreach (var image in maintenance.Images.Where(i => i.Status is "behind" or "newer-build"))
        {
            Line(md, $"- image `{image.Reference}`: {image.Status} {image.Current} → {image.Latest} ({image.Change}), used by {string.Join(", ", image.Apps)}");
        }

        if (maintenance.Truncated)
        {
            Line(md, "- … more: call get_maintenance.");
        }
    }

    private static void Line(StringBuilder md, string text) => md.Append(text).Append('\n');

    /// <summary>Keeps a value on one table cell: no pipe, no line break.</summary>
    private static string Cell(string value) => value.Replace('|', '/').ReplaceLineEndings(" ");

    private static string Number(double? value) => value is { } v ? v.ToString("0.##", CultureInfo.InvariantCulture) : "?";

    private static string Percent(double? value) => value is { } v ? $"{v.ToString("0.#", CultureInfo.InvariantCulture)} %" : "?";
}
